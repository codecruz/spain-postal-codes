// Generates data.js from the repository dataset (../../data). Run with: npm run build
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(packageDir, "..", "..", "data");

/** Minimal RFC 4180 parser: handles quoted fields containing commas and quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field !== "" || row.length > 0) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((values) => Object.fromEntries(header.map((key, i) => [key, values[i]])));
}

const rows = parseCsv(readFileSync(join(dataDir, "codigos_postales.csv"), "utf8"));
const provinces = parseCsv(readFileSync(join(dataDir, "provincias.csv"), "utf8"));
const metadata = JSON.parse(readFileSync(join(dataDir, "metadata.json"), "utf8"));

const municipalities = new Map();
for (const { cod_postal, municipio_id, municipio } of rows) {
  if (!/^\d{5}$/.test(cod_postal) || !/^\d{5}$/.test(municipio_id)) {
    throw new Error(`Invalid row: ${cod_postal},${municipio_id}`);
  }
  const entry = municipalities.get(municipio_id) ?? { name: municipio, codes: [] };
  entry.codes.push(cod_postal);
  municipalities.set(municipio_id, entry);
}

// Compact layout: [municipio_id, nombre, "cp1 cp2 ..."]; the province is the first two digits of the id.
const compact = [...municipalities]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, { name, codes }]) => [id, name, codes.sort().join(" ")]);

const meta = {
  period: metadata.source.period,
  referenceDate: metadata.source.reference_date,
  source: metadata.source.url,
  license: metadata.license,
  attribution: metadata.attribution,
};

const output = `// Generated by scripts/build-data.mjs from the INE dataset. Do not edit.
export const META = ${JSON.stringify(meta)};
export const PROVINCIAS = ${JSON.stringify(Object.fromEntries(provinces.map((p) => [p.provincia_id, p.provincia])))};
export const MUNICIPIOS = ${JSON.stringify(compact)};
`;

writeFileSync(join(packageDir, "data.js"), output);
console.error(`data.js: ${compact.length} municipalities, ${rows.length} postal code links (${(output.length / 1024).toFixed(0)} KB)`);
